/**
 * Ermittelt die bevorzugte Sprache anhand der eingestellten Browsersprache über chrome.i18n.getUILanguage().
 * Wird die Browsersprache unterstützt (de, en, fr, es), wird diese genutzt;
 * andernfalls dient Englisch ('en', entsprechend default_locale in manifest.json) als Standard.
 */
export function detectBrowserLanguage() {
  try {
    const raw =
      (typeof chrome !== 'undefined' && chrome.i18n && typeof chrome.i18n.getUILanguage === 'function'
        ? chrome.i18n.getUILanguage()
        : '') ||
      (typeof navigator !== 'undefined' ? navigator.language : '') ||
      'en';
    const short = String(raw).toLowerCase().split(/[-_]/)[0];
    if (short && Object.prototype.hasOwnProperty.call(TRANSLATIONS, short)) {
      return short;
    }
  } catch {
    // Fallback auf Englisch (default_locale)
  }
  return 'en';
}

export function resolveLanguageCode(lang) {
  if (!lang || lang === 'auto' || !TRANSLATIONS[lang]) {
    return detectBrowserLanguage();
  }
  return lang;
}

/**
 * Erzeugt eine Übersetzungsfunktion gemäß den Google chrome.i18n-Richtlinien:
 * - Im Standardmodus ('auto') wird vorrangig chrome.i18n.getMessage() (aus _locales/<locale>/messages.json
 *   mit Fallback auf default_locale "en") verwendet.
 * - Hat der Nutzer in den Einstellungen manuell eine feste Sprache gewählt, wird das entsprechende
 *   Sprachpaket direkt genutzt.
 */
export function createTranslator(lang = 'auto') {
  const isAuto = !lang || lang === 'auto' || !TRANSLATIONS[lang];
  const effectiveLang = resolveLanguageCode(lang);
  const dict = TRANSLATIONS[effectiveLang] || TRANSLATIONS.en;

  return (key) => {
    if (isAuto && typeof chrome !== 'undefined' && chrome.i18n && typeof chrome.i18n.getMessage === 'function') {
      try {
        const msg = chrome.i18n.getMessage(key);
        if (msg) return msg;
      } catch {
        // Fallback auf internes Wörterbuch
      }
    }
    return dict[key] ?? TRANSLATIONS.en[key] ?? key;
  };
}
